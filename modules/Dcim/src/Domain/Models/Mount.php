declare(strict_types=1);

namespace Modules\Dcim\Domain\Models;

use Illuminate\Database\Eloquent\Attributes\Table;
use Illuminate\Database\Eloquent\Attributes\UseFactory;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Carbon;
use Modules\Core\Domain\Concerns\Auditable;
use Modules\Core\Domain\Concerns\BelongsToOrganization;
use Modules\Core\Domain\Concerns\TracksAuthors;
use Modules\Dcim\Database\Factories\MountFactory;
use Modules\Dcim\Domain\Enums\MountFace;

/**
 * An asset of the asset register mounted in a rack.
 *
 * @property string $id
 * @property string $organization_id
 * @property string $rack_id
 * @property string $asset_id
 * @property ?int $position_u
 * @property int $height_u
 * @property MountFace $face
 * @property bool $full_depth
 * @property ?int $power_watts
 * @property ?string $notes
 * @property ?string $created_by
 * @property ?string $updated_by
 * @property Carbon $created_at
 * @property Carbon $updated_at
 * @property-read Rack $rack
 */
#[Table('dcim_mounts')]
#[UseFactory(MountFactory::class)]
final class Mount extends Model
{
    use Auditable;
    use BelongsToOrganization;

    /** @use HasFactory<MountFactory> */
    use HasFactory;

    use HasUuids;
    use TracksAuthors;

    protected $attributes = [
        'height_u' => 1,
        'face' => 'front',
        'full_depth' => true,
    ];

    /** Generated by the database for its exclusion constraints; never written. */
    protected $guarded = ['front_units', 'rear_units'];

    /**
     * @return BelongsTo<Rack, $this>
     */
    public function rack(): BelongsTo
    {
        return $this->belongsTo(Rack::class);
    }

    /**
     * @return HasMany<Port, $this>
     */
    public function ports(): HasMany
    {
        return $this->hasMany(Port::class)->orderBy('side')->orderBy('position');
    }

    public function isZeroU(): bool
    {
        return $this->position_u === null;
    }

    public function topUnit(): ?int
    {
        return $this->position_u === null ? null : $this->position_u + $this->height_u - 1;
    }

    /**
     * @return list<int>
     */
    public function units(): array
    {
        return $this->position_u === null ? [] : range($this->position_u, $this->position_u + $this->height_u - 1);
    }

    /**
     * Whether it takes these units on this side.
     */
    public function occupies(MountFace $face): bool
    {
        return $this->position_u !== null && ($this->full_depth || $this->face === $face);
    }

    /**
     * "U10–U11" or "U10"; "0U" on the rack's side.
     */
    public function unitsLabel(): string
    {
        return match (true) {
            $this->position_u === null => __('dcim::racks.zero_u'),
            $this->height_u === 1 => 'U'.$this->position_u,
            default => 'U'.$this->position_u.'–U'.$this->topUnit(),
        };
    }

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'position_u' => 'integer',
            'height_u' => 'integer',
            'face' => MountFace::class,
            'full_depth' => 'boolean',
            'power_watts' => 'integer',
        ];
    }
}
