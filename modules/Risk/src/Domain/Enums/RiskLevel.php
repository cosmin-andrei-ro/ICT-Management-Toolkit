declare(strict_types=1);

namespace Modules\Risk\Domain\Enums;

/**
 * Bands of likelihood × impact, set per organization (RiskSettings).
 */
enum RiskLevel: string
{
    case Low = 'low';
    case Medium = 'medium';
    case High = 'high';
    case Critical = 'critical';

    public function label(): string
    {
        return __('risk::risks.levels.'.$this->value);
    }
}
