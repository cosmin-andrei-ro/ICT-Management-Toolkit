declare(strict_types=1);

namespace Modules\Ticketing\Domain\Models;

use Illuminate\Database\Eloquent\Attributes\Table;
use Illuminate\Database\Eloquent\Attributes\UseFactory;
use Illuminate\Database\Eloquent\Attributes\UsePolicy;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasOne;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;
use Modules\Core\Domain\Concerns\Auditable;
use Modules\Core\Domain\Concerns\BelongsToOrganization;
use Modules\Core\Domain\Concerns\HasAttachments;
use Modules\Core\Domain\Concerns\HasComments;
use Modules\Core\Domain\Concerns\HasTags;
use Modules\Core\Domain\Concerns\Taggable;
use Modules\Core\Domain\Concerns\TracksAuthors;
use Modules\Core\Domain\Models\User;
use Modules\Ticketing\Application\Policies\TicketPolicy;
use Modules\Ticketing\Database\Factories\TicketFactory;
use Modules\Ticketing\Domain\Enums\Impact;
use Modules\Ticketing\Domain\Enums\Priority;
use Modules\Ticketing\Domain\Enums\ResolutionCode;
use Modules\Ticketing\Domain\Enums\TicketChannel;
use Modules\Ticketing\Domain\Enums\TicketStatus;
use Modules\Ticketing\Domain\Enums\TicketType;
use Modules\Ticketing\Domain\Enums\Urgency;

/**
 * Nothing is mass assignable: status, priority, assignment and resolution change
 * only through the actions in Application\Actions, which enforce the workflow.
 *
 * @property string $id
 * @property string $organization_id
 * @property string $number
 * @property TicketType $type
 * @property string $title
 * @property string $description
 * @property TicketStatus $status
 * @property Impact $impact
 * @property Urgency $urgency
 * @property Priority $priority
 * @property TicketChannel $channel
 * @property ?string $requester_id Null once anonymized (retention, ADR 0060).
 * @property ?Carbon $anonymized_at
 * @property ?string $assignee_id
 * @property ?string $queue_id
 * @property ?string $category_id
 * @property ?string $service_id
 * @property ?string $problem_id
 * @property ?Carbon $first_responded_at
 * @property ?Carbon $resolved_at
 * @property ?Carbon $closed_at
 * @property ?ResolutionCode $resolution_code
 * @property ?string $resolution_note
 * @property int $reopened_count
 * @property array<string, mixed> $custom_fields
 * @property ?string $created_by
 * @property ?string $updated_by
 * @property ?Carbon $created_at
 * @property ?Carbon $updated_at
 * @property ?Carbon $deleted_at
 * @property-read ?User $requester
 * @property-read ?User $assignee
 * @property-read ?Queue $queue
 * @property-read ?Category $category
 * @property-read ?Service $service
 * @property-read ?Ticket $problem
 * @property-read ?ProblemDetails $problemDetails
 * @property-read ?ChangeDetails $changeDetails
 */
#[Table('ticketing_tickets')]
#[UseFactory(TicketFactory::class)]
#[UsePolicy(TicketPolicy::class)]
final class Ticket extends Model implements Taggable
{
    use Auditable;
    use BelongsToOrganization;
    use HasAttachments;
    use HasComments;

    /** @use HasFactory<TicketFactory> */
    use HasFactory;

    use HasTags;
    use HasUuids;
    use SoftDeletes;
    use TracksAuthors;

    /**
     * Generated by PostgreSQL; never written or serialized.
     *
     * @var list<string>
     */
    protected $hidden = ['search_vector'];

    /**
     * @return list<string>
     */
    public function auditExclude(): array
    {
        return ['search_vector'];
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function requester(): BelongsTo
    {
        return $this->belongsTo(User::class, 'requester_id');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function assignee(): BelongsTo
    {
        return $this->belongsTo(User::class, 'assignee_id');
    }

    /**
     * @return BelongsTo<Queue, $this>
     */
    public function queue(): BelongsTo
    {
        return $this->belongsTo(Queue::class);
    }

    /**
     * @return BelongsTo<Category, $this>
     */
    public function category(): BelongsTo
    {
        return $this->belongsTo(Category::class);
    }

    /**
     * The problem behind this incident.
     *
     * @return BelongsTo<self, $this>
     */
    public function problem(): BelongsTo
    {
        return $this->belongsTo(self::class, 'problem_id');
    }

    /**
     * Incidents caused by this problem.
     *
     * @return HasMany<self, $this>
     */
    public function incidents(): HasMany
    {
        return $this->hasMany(self::class, 'problem_id');
    }

    /**
     * @return HasOne<ProblemDetails, $this>
     */
    public function problemDetails(): HasOne
    {
        return $this->hasOne(ProblemDetails::class, 'ticket_id');
    }

    /**
     * @return HasOne<ChangeDetails, $this>
     */
    public function changeDetails(): HasOne
    {
        return $this->hasOne(ChangeDetails::class, 'ticket_id');
    }

    /**
     * @return HasMany<ChangeApproval, $this>
     */
    public function changeApprovals(): HasMany
    {
        return $this->hasMany(ChangeApproval::class);
    }

    /**
     * @return BelongsTo<Service, $this>
     */
    public function service(): BelongsTo
    {
        return $this->belongsTo(Service::class);
    }

    /**
     * Answers to the service form, as stored at request time (labels included).
     *
     * @return list<array{key: string, label: string, type: string, value: mixed}>
     */
    public function serviceAnswers(): array
    {
        $stored = $this->custom_fields['service_form'] ?? [];
        $answers = [];

        foreach (is_array($stored) ? $stored : [] as $answer) {
            if (is_array($answer) && is_string($answer['key'] ?? null) && is_string($answer['label'] ?? null) && is_string($answer['type'] ?? null)) {
                $answers[] = ['key' => $answer['key'], 'label' => $answer['label'], 'type' => $answer['type'], 'value' => $answer['value'] ?? null];
            }
        }

        return $answers;
    }

    /**
     * @return BelongsToMany<User, $this>
     */
    public function watchers(): BelongsToMany
    {
        return $this->belongsToMany(User::class, 'ticketing_ticket_watchers')->withTimestamps();
    }

    /**
     * @return HasMany<SlaTimer, $this>
     */
    public function slaTimers(): HasMany
    {
        return $this->hasMany(SlaTimer::class);
    }

    /**
     * @return HasMany<StatusTransition, $this>
     */
    public function statusTransitions(): HasMany
    {
        return $this->hasMany(StatusTransition::class)->oldest();
    }

    public function isRequester(User $user): bool
    {
        return $this->requester_id === $user->id;
    }

    public function isWatchedBy(User $user): bool
    {
        return $this->watchers()->whereKey($user->id)->exists();
    }

    /**
     * Tickets a requester may see: their own and those they watch.
     *
     * @param  Builder<self>  $query
     */
    public function scopeVisibleToRequester(Builder $query, User $user): void
    {
        // Problems are internal to IT support and never appear in the portal.
        $query->whereIn('type', TicketType::requestable())
            ->where(fn (Builder $inner) => $inner
                ->where('requester_id', $user->id)
                ->orWhereHas('watchers', fn (Builder $watchers) => $watchers->whereKey($user->id)));
    }

    /**
     * PostgreSQL full-text search (websearch syntax: quotes, OR, -exclusion).
     *
     * @param  Builder<self>  $query
     */
    public function scopeSearch(Builder $query, string $terms): void
    {
        $terms = trim($terms);

        if ($terms === '') {
            return;
        }

        $query->where(fn (Builder $inner) => $inner
            ->whereRaw("search_vector @@ websearch_to_tsquery('english', ?)", [$terms])
            ->orWhereRaw("search_vector @@ websearch_to_tsquery('simple', ?)", [$terms]));
    }

    protected function casts(): array
    {
        return [
            'type' => TicketType::class,
            'status' => TicketStatus::class,
            'impact' => Impact::class,
            'urgency' => Urgency::class,
            'priority' => Priority::class,
            'channel' => TicketChannel::class,
            'resolution_code' => ResolutionCode::class,
            'first_responded_at' => 'datetime',
            'resolved_at' => 'datetime',
            'closed_at' => 'datetime',
            'anonymized_at' => 'datetime',
            'reopened_count' => 'integer',
            'custom_fields' => 'array',
        ];
    }
}
