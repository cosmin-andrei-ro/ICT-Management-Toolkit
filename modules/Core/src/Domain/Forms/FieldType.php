declare(strict_types=1);

namespace Modules\Core\Domain\Forms;

enum FieldType: string
{
    case Text = 'text';
    case Textarea = 'textarea';
    case Number = 'number';
    case Date = 'date';
    case Select = 'select';
    case Checkbox = 'checkbox';

    public function label(): string
    {
        return __('core::forms.types.'.$this->value);
    }
}
